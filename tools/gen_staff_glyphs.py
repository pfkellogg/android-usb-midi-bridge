"""Turns the music symbols the note popup's staff needs (treble and bass clef,
sharp, whole note) from Noto Music into flattened outlines, so the app draws
them itself on any device, whatever its fonts.

    pip install fonttools
    python3 tools/gen_staff_glyphs.py NotoMusic-Regular.ttf

Writes app/src/main/java/com/fm1/midibridge/StaffGlyphs.java and prints the
same data as Python for mac_midi_bridge/staff_glyphs.py.

Noto Music: 1000 units per em = 4 staff spaces, baseline = bottom staff line.
Output is in staff spaces, y down. Clefs keep the baseline at y = 0 (and
x = 0 at their left edge); the sharp and the note head are centred on (0, 0).
"""
import sys
from fontTools.ttLib import TTFont
from fontTools.pens.basePen import BasePen
from fontTools.pens.boundsPen import BoundsPen

SPACE = 250.0
STEPS = 6  # line segments per curve
GLYPHS = [("G_CLEF", 0x1D11E, False), ("F_CLEF", 0x1D122, False),
          ("SHARP", 0x266F, True), ("WHOLE", 0x1D15D, True)]


class Flatten(BasePen):
    def __init__(self, gs):
        super().__init__(gs)
        self.contours, self.cur = [], None

    def _moveTo(self, p):
        self.cur = [p]

    def _lineTo(self, p):
        self.cur.append(p)

    def _qCurveToOne(self, c, p):
        x0, y0 = self.cur[-1]
        for i in range(1, STEPS + 1):
            t = i / STEPS
            a, b, d = (1 - t) ** 2, 2 * t * (1 - t), t * t
            self.cur.append((a * x0 + b * c[0] + d * p[0], a * y0 + b * c[1] + d * p[1]))

    def _curveToOne(self, c1, c2, p):
        x0, y0 = self.cur[-1]
        for i in range(1, STEPS + 1):
            t = i / STEPS
            a, b, c, d = (1 - t) ** 3, 3 * t * (1 - t) ** 2, 3 * t * t * (1 - t), t ** 3
            self.cur.append((a * x0 + b * c1[0] + c * c2[0] + d * p[0],
                             a * y0 + b * c1[1] + c * c2[1] + d * p[1]))

    def _closePath(self):
        self.contours.append(self.cur)
        self.cur = None

    _endPath = _closePath


def glyph(font, cp, centred):
    gs = font.getGlyphSet()
    name = font.getBestCmap()[cp]
    bp = BoundsPen(gs)
    gs[name].draw(bp)
    x0, y0, x1, y1 = bp.bounds
    pen = Flatten(gs)
    gs[name].draw(pen)
    dx, dy = ((x0 + x1) / 2, (y0 + y1) / 2) if centred else (x0, 0)
    out = []
    for c in pen.contours:
        pts = []
        for x, y in c:
            pts += [round((x - dx) / SPACE, 3), round(-(y - dy) / SPACE, 3)]
        out.append(pts)
    return out, round((x1 - x0) / SPACE, 3)


def main(path):
    font = TTFont(path)
    java = ["package com.fm1.midibridge;", "",
            "/** Generated by tools/gen_staff_glyphs.py from Noto Music (SIL Open Font License). Don't edit. */",
            "final class StaffGlyphs {", "", "    private StaffGlyphs() {", "    }", ""]
    py = ['"""Generated by android_midi_bridge/tools/gen_staff_glyphs.py from Noto Music',
          '(SIL Open Font License). Outlines in staff spaces, y down. Don\'t edit."""', ""]
    for name, cp, centred in GLYPHS:
        contours, width = glyph(font, cp, centred)
        java.append(f"    static final float {name}_WIDTH = {width}f;")
        java.append(f"    static final float[][] {name} = {{")
        for c in contours:
            java.append("        {" + ", ".join(f"{v}f" for v in c) + "},")
        java += ["    };", ""]
        py.append(f"{name}_WIDTH = {width}")
        py.append(f"{name} = [")
        for c in contours:
            py.append("    [" + ", ".join(str(v) for v in c) + "],")
        py += ["]", ""]
    java.append("}")
    open("app/src/main/java/com/fm1/midibridge/StaffGlyphs.java", "w").write("\n".join(java) + "\n")
    print("\n".join(py))


if __name__ == "__main__":
    main(sys.argv[1])
